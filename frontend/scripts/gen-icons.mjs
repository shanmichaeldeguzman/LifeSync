/**
 * Scans the app (and the DB seed in the migrations) for ionicon names and generates
 * src/app/icons.ts, which registers exactly the icons LifeSync uses. Standalone
 * Ionic requires icons to be registered explicitly; this keeps the bundle small
 * and guarantees no icon renders blank.
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDts = readFileSync(join(root, 'node_modules/ionicons/icons/index.d.ts'), 'utf8');
const available = new Set([...iconsDts.matchAll(/export declare var (\w+): string;/g)].map((m) => m[1]));

const toCamel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(ts|html)$/.test(name) && !name.endsWith('icons.ts')) out.push(p);
  }
  return out;
}

const sources = walk(join(root, 'src/app'));
const migrations = join(root, '../supabase/migrations');
if (existsSync(migrations)) for (const f of readdirSync(migrations)) sources.push(join(migrations, f));

const found = new Set();
for (const file of sources) {
  const text = readFileSync(file, 'utf8');
  for (const m of text.matchAll(/["'`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["'`]/g)) {
    const camel = toCamel(m[1]);
    if (available.has(camel) && (m[1].includes('-') || ['add', 'close', 'checkmark', 'sync', 'flame', 'star', 'pin', 'image', 'apps'].includes(m[1]))) {
      found.add(camel);
    }
  }
}
const list = [...found].sort();

const out = `// AUTO-GENERATED by scripts/gen-icons.mjs, do not edit.
import { addIcons } from 'ionicons';
import {
${list.map((i) => `  ${i},`).join('\n')}
} from 'ionicons/icons';

/** Registers every ionicon used by LifeSync (including icons stored on categories). */
export function registerIcons(): void {
  addIcons({
${list.map((i) => `    '${i.replace(/[A-Z0-9]/g, (c) => '-' + c.toLowerCase())}': ${i},`).join('\n')}
  });
}
`;
writeFileSync(join(root, 'src/app/icons.ts'), out);
console.log(`[gen-icons] Registered ${list.length} icons`);
